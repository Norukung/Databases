CREATE OR REPLACE PACKAGE BODY GINGER_API AS
  FUNCTION HOTEL_DAY RETURN DATE IS BEGIN
    RETURN TRUNC(CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS DATE));
  END;
  PROCEDURE REQUIRE_VALUE(p_ok BOOLEAN, p_code NUMBER, p_message VARCHAR2) IS BEGIN
    IF p_ok IS NULL OR NOT p_ok THEN RAISE_APPLICATION_ERROR(p_code,p_message); END IF;
  END;
  PROCEDURE AUTHORIZE(p_account NUMBER,p_need VARCHAR2,p_customer OUT NUMBER,p_employee OUT NUMBER) IS
    v_role VARCHAR2(10); v_pay NUMBER; v_cancel NUMBER; v_active NUMBER;
  BEGIN
    SELECT a.CUSTOMER_ID,a.EMPLOYEE_ID,NVL(e.SYSTEM_ROLE,'USER'),a.CAN_REVIEW_PAYMENTS,
      a.CAN_REVIEW_CANCELLATIONS,CASE WHEN a.CUSTOMER_ID IS NOT NULL THEN CASE WHEN c.DELETED_AT IS NULL THEN 1 ELSE 0 END ELSE CASE WHEN e.DELETED_AT IS NULL THEN 1 ELSE 0 END END
    INTO p_customer,p_employee,v_role,v_pay,v_cancel,v_active FROM WEB_ACCOUNTS a
    LEFT JOIN CUSTOMERS c ON c.CUSTOMER_ID=a.CUSTOMER_ID
    LEFT JOIN EMPLOYEES e ON e.EMPLOYEE_ID=a.EMPLOYEE_ID
    WHERE a.ACCOUNT_ID=p_account AND a.IS_ACTIVE=1;
    REQUIRE_VALUE(v_active=1,-20001,'FORBIDDEN: inactive owner');
    REQUIRE_VALUE(p_need='OWN' OR (p_need='STAFF' AND v_role IN ('STAFF','ADMIN'))
      OR (p_need='ADMIN' AND v_role='ADMIN')
      OR (p_need='PAYMENT' AND (v_role='ADMIN' OR (v_role='STAFF' AND v_pay=1)))
      OR (p_need='CANCEL' AND (v_role='ADMIN' OR (v_role='STAFF' AND v_cancel=1))),-20001,'FORBIDDEN');
  EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20001,'UNAUTHENTICATED'); END;
  PROCEDURE CHECK_OWNER(p_customer NUMBER,p_employee NUMBER,p_booking BOOKINGS%ROWTYPE) IS BEGIN
    REQUIRE_VALUE(p_employee IS NOT NULL OR p_customer=p_booking.CUSTOMER_ID,-20002,'NOT_FOUND');
  END;
  PROCEDURE AUDIT_EVENT(p_account NUMBER,p_action VARCHAR2,p_table VARCHAR2,p_id NUMBER,p_details VARCHAR2 DEFAULT NULL) IS BEGIN
    INSERT INTO AUDIT_LOG(ACCOUNT_ID,ACTION_NAME,ENTITY_NAME,ENTITY_ID,DETAILS)
    VALUES(p_account,p_action,p_table,p_id,p_details);
  END;
  -- Lock each physical room separately in increasing ID order. All allocation
  -- mutators use this order before BOOKINGS, PAYMENTS, REQUESTS and REFUNDS.
  PROCEDURE LOCK_ROOM(p_room NUMBER) IS v_id NUMBER; BEGIN
    SELECT ROOM_ID INTO v_id FROM ROOMS WHERE ROOM_ID=p_room FOR UPDATE WAIT 5;
  END;
  PROCEDURE LOCK_BOOKING(p_booking NUMBER,p_row OUT BOOKINGS%ROWTYPE) IS BEGIN
    FOR r IN (SELECT ROOM_ID FROM BOOKING_ROOMS WHERE BOOKING_ID=p_booking ORDER BY ROOM_ID) LOOP LOCK_ROOM(r.ROOM_ID); END LOOP;
    SELECT * INTO p_row FROM BOOKINGS WHERE BOOKING_ID=p_booking FOR UPDATE WAIT 5;
  END;
  FUNCTION PAID_AMOUNT(p_booking NUMBER) RETURN NUMBER IS v_sum NUMBER; BEGIN
    SELECT NVL(SUM(AMOUNT),0) INTO v_sum FROM PAYMENTS WHERE BOOKING_ID=p_booking AND PAYMENT_STATUS='PAID'; RETURN v_sum;
  END;
  FUNCTION REVIEW_COUNT(p_booking NUMBER) RETURN NUMBER IS v_count NUMBER; BEGIN
    SELECT COUNT(*) INTO v_count FROM PAYMENTS WHERE BOOKING_ID=p_booking AND PAYMENT_STATUS='UNDER_REVIEW'; RETURN v_count;
  END;
  FUNCTION ROOM_CONFLICTS(p_room NUMBER,p_start DATE,p_end DATE) RETURN NUMBER IS v_count NUMBER; v_day DATE:=HOTEL_DAY; BEGIN
    SELECT COUNT(*) INTO v_count FROM BOOKING_ROOMS br JOIN BOOKINGS b ON b.BOOKING_ID=br.BOOKING_ID
    WHERE br.ROOM_ID=p_room
      AND (b.BOOKING_STATUS IN ('CONFIRMED','CHECKED_IN') OR (b.BOOKING_STATUS='PENDING_PAYMENT'
        AND (b.EXPIRES_AT>CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP) OR EXISTS (SELECT 1 FROM PAYMENTS p WHERE p.BOOKING_ID=b.BOOKING_ID AND p.PAYMENT_STATUS='UNDER_REVIEW'))))
      AND ((b.CHECK_IN_DATE<p_end AND b.CHECK_OUT_DATE>p_start)
        OR (b.BOOKING_STATUS='CHECKED_IN' AND b.CHECK_OUT_DATE<=v_day AND p_start=v_day));
    RETURN v_count;
  END;
  PROCEDURE CHECK_OPEN_BOOKING(p_row BOOKINGS%ROWTYPE) IS BEGIN
    REQUIRE_VALUE(p_row.BOOKING_STATUS IN ('PENDING_PAYMENT','CONFIRMED','CHECKED_IN'),-20003,'INVALID_STATE');
    IF p_row.BOOKING_STATUS='PENDING_PAYMENT' THEN
      REQUIRE_VALUE(p_row.EXPIRES_AT>CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP) OR REVIEW_COUNT(p_row.BOOKING_ID)>0,-20004,'BOOKING_EXPIRED');
    END IF;
  END;

  PROCEDURE CREATE_BOOKING(p_account NUMBER,p_customer NUMBER,p_check_in DATE,p_check_out DATE,
    p_guests NUMBER,p_room_ids CLOB,p_services CLOB,p_promotion NUMBER,p_expected_total NUMBER,p_booking_id OUT NUMBER) IS
    v_customer NUMBER; v_employee NUMBER; v_id NUMBER; v_count NUMBER; v_unique NUMBER; v_capacity NUMBER:=0;
    v_room_amount NUMBER:=0; v_service_amount NUMBER:=0; v_discount NUMBER:=0; v_percent NUMBER:=0;
    v_price NUMBER; v_max NUMBER; v_active NUMBER; v_status VARCHAR2(20); v_min_nights NUMBER; v_min_amount NUMBER;
    v_start DATE; v_end DATE; v_total NUMBER; v_days NUMBER;
    v_room_array JSON_ARRAY_T; v_service_array JSON_ARRAY_T;
  BEGIN
    AUTHORIZE(p_account,'OWN',v_customer,v_employee);
    IF v_employee IS NOT NULL THEN v_customer:=p_customer; END IF;
    SELECT CASE WHEN DELETED_AT IS NULL THEN 1 ELSE 0 END INTO v_active FROM CUSTOMERS WHERE CUSTOMER_ID=v_customer;
    REQUIRE_VALUE(v_active=1,-20005,'INVALID_CUSTOMER');
    REQUIRE_VALUE(p_check_in=TRUNC(p_check_in) AND p_check_out=TRUNC(p_check_out)
      AND p_check_in>=HOTEL_DAY AND p_check_out>p_check_in AND p_check_out-p_check_in<=30,-20006,'INVALID_DATES');
    v_days:=p_check_out-p_check_in;
    -- JSON_TABLE's default document handling must not turn malformed services
    -- into an empty order. Parsing as JSON_ARRAY_T rejects non-array documents.
    v_room_array:=JSON_ARRAY_T.PARSE(p_room_ids);
    v_service_array:=JSON_ARRAY_T.PARSE(p_services);
    REQUIRE_VALUE(v_room_array.GET_SIZE() BETWEEN 1 AND 10,-20007,'INVALID_ROOMS');
    REQUIRE_VALUE(v_service_array.GET_SIZE()<=100,-20010,'INVALID_SERVICES');
    SELECT COUNT(*),COUNT(DISTINCT room_id) INTO v_count,v_unique
      FROM JSON_TABLE(p_room_ids,'$[*]' COLUMNS(room_id NUMBER PATH '$' ERROR ON ERROR));
    REQUIRE_VALUE(v_count BETWEEN 1 AND 10 AND v_count=v_unique,-20007,'INVALID_ROOMS');
    REQUIRE_VALUE(p_guests=TRUNC(p_guests) AND p_guests>=v_count AND p_guests<=999,-20008,'INVALID_GUESTS');
    FOR r IN (SELECT room_id FROM JSON_TABLE(p_room_ids,'$[*]' COLUMNS(room_id NUMBER PATH '$' ERROR ON ERROR)) ORDER BY room_id) LOOP
      REQUIRE_VALUE(r.room_id=TRUNC(r.room_id),-20007,'INVALID_ROOM_ID');
      LOCK_ROOM(r.room_id);
    END LOOP;
    -- Lock catalogue rows in deterministic order too, so the later inserts use
    -- exactly the prices that were validated and included in the total.
    FOR rt IN (SELECT DISTINCT ROOM_TYPE_ID FROM ROOMS WHERE ROOM_ID IN
      (SELECT room_id FROM JSON_TABLE(p_room_ids,'$[*]' COLUMNS(room_id NUMBER PATH '$' ERROR ON ERROR))) ORDER BY ROOM_TYPE_ID) LOOP
      SELECT ROOM_TYPE_ID INTO v_id FROM ROOM_TYPES WHERE ROOM_TYPE_ID=rt.ROOM_TYPE_ID FOR UPDATE WAIT 5;
    END LOOP;
    FOR svc IN (SELECT DISTINCT service_id FROM JSON_TABLE(p_services,'$[*]' COLUMNS(service_id NUMBER PATH '$.serviceId' ERROR ON ERROR)) ORDER BY service_id) LOOP
      SELECT SERVICE_ID INTO v_id FROM SERVICES WHERE SERVICE_ID=svc.service_id FOR UPDATE WAIT 5;
    END LOOP;
    IF p_promotion IS NOT NULL THEN
      SELECT PROMOTION_ID INTO v_id FROM PROMOTIONS WHERE PROMOTION_ID=p_promotion FOR UPDATE WAIT 5;
    END IF;
    -- Re-query availability after acquiring ALL room locks.
    FOR selected_room IN (SELECT room_id FROM JSON_TABLE(p_room_ids,'$[*]' COLUMNS(room_id NUMBER PATH '$' ERROR ON ERROR)) ORDER BY room_id) LOOP
      SELECT t.PRICE_PER_NIGHT,t.MAX_GUESTS,CASE WHEN rm.IS_ACTIVE=1 AND t.DELETED_AT IS NULL THEN 1 ELSE 0 END,rm.ROOM_STATUS
      INTO v_price,v_max,v_active,v_status FROM ROOMS rm JOIN ROOM_TYPES t ON t.ROOM_TYPE_ID=rm.ROOM_TYPE_ID WHERE rm.ROOM_ID=selected_room.room_id;
      REQUIRE_VALUE(v_active=1 AND v_status<>'MAINTENANCE' AND ROOM_CONFLICTS(selected_room.room_id,p_check_in,p_check_out)=0,-20009,'ROOM_UNAVAILABLE');
      SELECT COUNT(*) INTO v_count FROM ROOM_MAINTENANCE WHERE ROOM_ID=selected_room.room_id AND START_DATE<p_check_out AND END_DATE>p_check_in;
      REQUIRE_VALUE(v_count=0,-20009,'ROOM_MAINTENANCE');
      v_room_amount:=v_room_amount+v_price*v_days; v_capacity:=v_capacity+v_max;
    END LOOP;
    REQUIRE_VALUE(p_guests<=v_capacity,-20008,'CAPACITY_EXCEEDED');
    SELECT COUNT(*),COUNT(DISTINCT service_id) INTO v_count,v_unique FROM JSON_TABLE(p_services,'$[*]' COLUMNS(service_id NUMBER PATH '$.serviceId' ERROR ON ERROR));
    REQUIRE_VALUE(v_count=v_unique AND v_count<=100,-20010,'DUPLICATE_SERVICE');
    FOR item IN (SELECT service_id,quantity FROM JSON_TABLE(p_services,'$[*]' COLUMNS(service_id NUMBER PATH '$.serviceId' ERROR ON ERROR,quantity NUMBER PATH '$.quantity' ERROR ON ERROR))) LOOP
      REQUIRE_VALUE(item.quantity=TRUNC(item.quantity) AND item.quantity BETWEEN 1 AND 99,-20010,'INVALID_SERVICE_QUANTITY');
      SELECT UNIT_PRICE,CASE WHEN DELETED_AT IS NULL AND SERVICE_STATUS='ACTIVE' THEN 1 ELSE 0 END INTO v_price,v_active FROM SERVICES WHERE SERVICE_ID=item.service_id;
      REQUIRE_VALUE(v_active=1,-20010,'SERVICE_DISABLED'); v_service_amount:=v_service_amount+v_price*item.quantity;
    END LOOP;
    IF p_promotion IS NOT NULL THEN
      SELECT DISCOUNT_PERCENT,MIN_NIGHTS,MIN_ROOM_AMOUNT,START_DATE,END_DATE,CASE WHEN DELETED_AT IS NULL THEN 1 ELSE 0 END
        INTO v_percent,v_min_nights,v_min_amount,v_start,v_end,v_active FROM PROMOTIONS WHERE PROMOTION_ID=p_promotion;
      REQUIRE_VALUE(v_active=1 AND HOTEL_DAY BETWEEN v_start AND v_end AND v_days>=v_min_nights AND v_room_amount>=v_min_amount,-20011,'PROMOTION_INELIGIBLE');
      v_discount:=ROUND(v_room_amount*v_percent/100,2);
    END IF;
    v_total:=v_room_amount+v_service_amount-v_discount;
    REQUIRE_VALUE(v_total>0 AND p_expected_total=v_total,-20012,'PRICE_CHANGED');
    INSERT INTO BOOKINGS(CUSTOMER_ID,EMPLOYEE_ID,PROMOTION_ID,CHECK_IN_DATE,CHECK_OUT_DATE,GUEST_COUNT,BOOKING_STATUS,EXPIRES_AT,ROOM_AMOUNT,SERVICE_AMOUNT,DISCOUNT_AMOUNT,TOTAL_AMOUNT,DISCOUNT_PERCENT_AT_BOOKING)
    VALUES(v_customer,v_employee,p_promotion,p_check_in,p_check_out,p_guests,'PENDING_PAYMENT',CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP)+INTERVAL '1' DAY,v_room_amount,v_service_amount,v_discount,v_total,v_percent)
    RETURNING BOOKING_ID INTO p_booking_id;
    -- Catalogue locks above preserve the validated snapshot prices.
    FOR item IN (SELECT rm.ROOM_ID,t.PRICE_PER_NIGHT FROM ROOMS rm JOIN ROOM_TYPES t ON t.ROOM_TYPE_ID=rm.ROOM_TYPE_ID
      WHERE rm.ROOM_ID IN (SELECT room_id FROM JSON_TABLE(p_room_ids,'$[*]' COLUMNS(room_id NUMBER PATH '$' ERROR ON ERROR)))) LOOP
      INSERT INTO BOOKING_ROOMS(BOOKING_ID,ROOM_ID,AGREED_PRICE_PER_NIGHT) VALUES(p_booking_id,item.ROOM_ID,item.PRICE_PER_NIGHT);
    END LOOP;
    FOR item IN (SELECT j.service_id,j.quantity,s.UNIT_PRICE FROM JSON_TABLE(p_services,'$[*]' COLUMNS(service_id NUMBER PATH '$.serviceId' ERROR ON ERROR,quantity NUMBER PATH '$.quantity' ERROR ON ERROR)) j JOIN SERVICES s ON s.SERVICE_ID=j.service_id) LOOP
      INSERT INTO SERVICE_USAGE(BOOKING_ID,SERVICE_ID,QUANTITY,UNIT_PRICE_AT_USE,USAGE_DATE,USAGE_STATUS,RECORDED_BY)
      VALUES(p_booking_id,item.service_id,item.quantity,item.UNIT_PRICE,p_check_in,'PLANNED',v_employee);
    END LOOP;
    INSERT INTO PAYMENTS(BOOKING_ID,AMOUNT,PAYMENT_STATUS) VALUES(p_booking_id,v_total,'PENDING');
    AUDIT_EVENT(p_account,'CREATE_BOOKING','BOOKINGS',p_booking_id);
    COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE; END;

  PROCEDURE SUBMIT_PAYMENT(p_account NUMBER,p_booking NUMBER,p_amount NUMBER,p_method VARCHAR2,p_proof_key VARCHAR2,p_mime VARCHAR2,p_bytes NUMBER,p_payment_id OUT NUMBER) IS
    v_customer NUMBER; v_employee NUMBER; v_booking BOOKINGS%ROWTYPE;
  BEGIN
    AUTHORIZE(p_account,'OWN',v_customer,v_employee); LOCK_BOOKING(p_booking,v_booking); CHECK_OWNER(v_customer,v_employee,v_booking); CHECK_OPEN_BOOKING(v_booking);
    REQUIRE_VALUE(REVIEW_COUNT(p_booking)=0,-20013,'PAYMENT_ALREADY_UNDER_REVIEW');
    REQUIRE_VALUE(p_amount>0 AND p_amount=v_booking.TOTAL_AMOUNT-PAID_AMOUNT(p_booking),-20014,'AMOUNT_MISMATCH');
    REQUIRE_VALUE(p_method IN ('BANK_TRANSFER','PROMPTPAY') AND p_proof_key IS NOT NULL
      AND p_mime IN ('image/png','image/jpeg') AND p_bytes BETWEEN 1 AND 1048576,-20015,'INVALID_PROOF');
    -- Backend validates magic bytes, decodes image, scans, stores in private storage
    -- BEFORE invoking this procedure. p_proof_key is a trusted opaque storage key.
    BEGIN
      SELECT PAYMENT_ID INTO p_payment_id FROM PAYMENTS WHERE BOOKING_ID=p_booking AND PAYMENT_STATUS='PENDING' FOR UPDATE WAIT 5;
      UPDATE PAYMENTS SET AMOUNT=p_amount,PAYMENT_METHOD=p_method,PAYMENT_PROOF=p_proof_key,
        PROOF_MIME=p_mime,PROOF_BYTES=p_bytes,SUBMITTED_AT=CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP),PAYMENT_STATUS='UNDER_REVIEW' WHERE PAYMENT_ID=p_payment_id;
    EXCEPTION WHEN NO_DATA_FOUND THEN
      INSERT INTO PAYMENTS(BOOKING_ID,AMOUNT,PAYMENT_METHOD,PAYMENT_PROOF,PROOF_MIME,PROOF_BYTES,SUBMITTED_AT,PAYMENT_STATUS)
      VALUES(p_booking,p_amount,p_method,p_proof_key,p_mime,p_bytes,CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP),'UNDER_REVIEW') RETURNING PAYMENT_ID INTO p_payment_id;
    END;
    AUDIT_EVENT(p_account,'SUBMIT_PAYMENT','PAYMENTS',p_payment_id); COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE; END;

  PROCEDURE REVIEW_PAYMENT(p_account NUMBER,p_payment NUMBER,p_decision VARCHAR2,p_verified_amount NUMBER,p_note VARCHAR2) IS
    v_customer NUMBER; v_employee NUMBER; v_booking_id NUMBER; v_booking BOOKINGS%ROWTYPE; v_payment PAYMENTS%ROWTYPE;
  BEGIN
    AUTHORIZE(p_account,'PAYMENT',v_customer,v_employee);
    SELECT BOOKING_ID INTO v_booking_id FROM PAYMENTS WHERE PAYMENT_ID=p_payment;
    LOCK_BOOKING(v_booking_id,v_booking);
    SELECT * INTO v_payment FROM PAYMENTS WHERE PAYMENT_ID=p_payment FOR UPDATE WAIT 5;
    CHECK_OPEN_BOOKING(v_booking);
    REQUIRE_VALUE(v_payment.PAYMENT_STATUS='UNDER_REVIEW' AND v_payment.PAYMENT_PROOF IS NOT NULL,-20016,'PAYMENT_ALREADY_PROCESSED');
    REQUIRE_VALUE(p_decision IN ('APPROVE','REJECT') AND (p_note IS NULL OR LENGTH(p_note)<=500),-20017,'INVALID_DECISION');
    IF p_decision='APPROVE' THEN
      REQUIRE_VALUE(p_verified_amount=v_payment.AMOUNT AND v_payment.AMOUNT=v_booking.TOTAL_AMOUNT-PAID_AMOUNT(v_booking_id),-20014,'AMOUNT_MISMATCH');
      UPDATE PAYMENTS SET PAYMENT_STATUS='PAID',PAID_AT=CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP),REVIEWED_BY=v_employee,REVIEWED_AT=CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP),REVIEW_NOTE=p_note WHERE PAYMENT_ID=p_payment;
      UPDATE BOOKINGS SET BOOKING_STATUS=CASE WHEN BOOKING_STATUS='PENDING_PAYMENT' THEN 'CONFIRMED' ELSE BOOKING_STATUS END WHERE BOOKING_ID=v_booking_id;
    ELSE
      REQUIRE_VALUE(TRIM(p_note) IS NOT NULL,-20018,'REASON_REQUIRED');
      UPDATE PAYMENTS SET PAYMENT_STATUS='REJECTED',REVIEWED_BY=v_employee,REVIEWED_AT=CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP),REVIEW_NOTE=p_note WHERE PAYMENT_ID=p_payment;
      UPDATE BOOKINGS SET EXPIRES_AT=CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP)+INTERVAL '2' HOUR WHERE BOOKING_ID=v_booking_id AND BOOKING_STATUS='PENDING_PAYMENT';
    END IF;
    AUDIT_EVENT(p_account,'REVIEW_PAYMENT','PAYMENTS',p_payment,p_decision); COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE; END;

  PROCEDURE CHECK_IN(p_account NUMBER,p_booking NUMBER) IS
    v_customer NUMBER; v_employee NUMBER; v_booking BOOKINGS%ROWTYPE; v_count NUMBER; v_status VARCHAR2(20); v_active NUMBER;
  BEGIN
    AUTHORIZE(p_account,'STAFF',v_customer,v_employee); LOCK_BOOKING(p_booking,v_booking);
    REQUIRE_VALUE(v_booking.BOOKING_STATUS='CONFIRMED',-20003,'INVALID_STATE');
    REQUIRE_VALUE(HOTEL_DAY=v_booking.CHECK_IN_DATE AND
      CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS DATE)>=v_booking.CHECK_IN_DATE+14/24,-20019,'INVALID_CHECKIN_TIME');
    REQUIRE_VALUE(v_booking.TOTAL_AMOUNT=PAID_AMOUNT(p_booking),-20020,'OUTSTANDING_BALANCE');
    SELECT COUNT(*) INTO v_count FROM STAY_HISTORY WHERE BOOKING_ID=p_booking;
    REQUIRE_VALUE(v_count=0,-20021,'ALREADY_CHECKED_IN');
    FOR room IN (SELECT ROOM_ID FROM BOOKING_ROOMS WHERE BOOKING_ID=p_booking ORDER BY ROOM_ID) LOOP
      SELECT ROOM_STATUS,IS_ACTIVE INTO v_status,v_active FROM ROOMS WHERE ROOM_ID=room.ROOM_ID;
      SELECT COUNT(*) INTO v_count FROM STAY_HISTORY h JOIN BOOKING_ROOMS br ON br.BOOKING_ID=h.BOOKING_ID
      WHERE br.ROOM_ID=room.ROOM_ID AND h.ACTUAL_CHECK_OUT IS NULL;
      REQUIRE_VALUE(v_status='AVAILABLE' AND v_active=1 AND v_count=0,-20022,'ROOM_NOT_READY');
      SELECT COUNT(*) INTO v_count FROM ROOM_MAINTENANCE WHERE ROOM_ID=room.ROOM_ID AND START_DATE<v_booking.CHECK_OUT_DATE AND END_DATE>v_booking.CHECK_IN_DATE;
      REQUIRE_VALUE(v_count=0,-20022,'ROOM_NOT_READY');
    END LOOP;
    INSERT INTO STAY_HISTORY(BOOKING_ID,EMPLOYEE_ID,ACTUAL_CHECK_IN) VALUES(p_booking,v_employee,CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP));
    UPDATE BOOKINGS SET BOOKING_STATUS='CHECKED_IN' WHERE BOOKING_ID=p_booking;
    UPDATE ROOMS SET ROOM_STATUS='OCCUPIED' WHERE ROOM_ID IN (SELECT ROOM_ID FROM BOOKING_ROOMS WHERE BOOKING_ID=p_booking);
    AUDIT_EVENT(p_account,'CHECK_IN','BOOKINGS',p_booking); COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE; END;

  PROCEDURE CHECK_OUT(p_account NUMBER,p_booking NUMBER) IS
    v_customer NUMBER; v_employee NUMBER; v_booking BOOKINGS%ROWTYPE; v_count NUMBER;
  BEGIN
    AUTHORIZE(p_account,'STAFF',v_customer,v_employee); LOCK_BOOKING(p_booking,v_booking);
    REQUIRE_VALUE(v_booking.BOOKING_STATUS='CHECKED_IN',-20003,'INVALID_STATE');
    REQUIRE_VALUE(v_booking.TOTAL_AMOUNT=PAID_AMOUNT(p_booking),-20020,'OUTSTANDING_BALANCE');
    SELECT COUNT(*) INTO v_count FROM SERVICE_USAGE WHERE BOOKING_ID=p_booking AND USAGE_STATUS='PLANNED';
    REQUIRE_VALUE(v_count=0,-20023,'SERVICE_UNRESOLVED');
    UPDATE STAY_HISTORY SET ACTUAL_CHECK_OUT=CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP),CHECK_OUT_EMPLOYEE_ID=v_employee
    WHERE BOOKING_ID=p_booking AND ACTUAL_CHECK_OUT IS NULL;
    REQUIRE_VALUE(SQL%ROWCOUNT=1,-20024,'ALREADY_CHECKED_OUT');
    UPDATE BOOKINGS SET BOOKING_STATUS='CHECKED_OUT' WHERE BOOKING_ID=p_booking;
    UPDATE ROOMS SET ROOM_STATUS='CLEANING' WHERE ROOM_ID IN (SELECT ROOM_ID FROM BOOKING_ROOMS WHERE BOOKING_ID=p_booking);
    AUDIT_EVENT(p_account,'CHECK_OUT','BOOKINGS',p_booking); COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE; END;

  PROCEDURE ADD_SERVICE(p_account NUMBER,p_booking NUMBER,p_service NUMBER,p_quantity NUMBER,p_status VARCHAR2) IS
    v_customer NUMBER; v_employee NUMBER; v_booking BOOKINGS%ROWTYPE; v_price NUMBER; v_active NUMBER; v_id NUMBER; v_day DATE:=HOTEL_DAY;
  BEGIN
    AUTHORIZE(p_account,'STAFF',v_customer,v_employee); LOCK_BOOKING(p_booking,v_booking);
    REQUIRE_VALUE(v_booking.BOOKING_STATUS IN ('CONFIRMED','CHECKED_IN') AND p_status IN ('PLANNED','USED') AND
      (p_status<>'USED' OR v_booking.BOOKING_STATUS='CHECKED_IN'),-20003,'INVALID_STATE');
    REQUIRE_VALUE(p_quantity=TRUNC(p_quantity) AND p_quantity BETWEEN 1 AND 99,-20010,'INVALID_QUANTITY');
    REQUIRE_VALUE(REVIEW_COUNT(p_booking)=0,-20026,'REVIEW_PAYMENT_FIRST');
    SELECT UNIT_PRICE,CASE WHEN DELETED_AT IS NULL AND SERVICE_STATUS='ACTIVE' THEN 1 ELSE 0 END INTO v_price,v_active FROM SERVICES WHERE SERVICE_ID=p_service FOR UPDATE WAIT 5;
    REQUIRE_VALUE(v_active=1,-20010,'SERVICE_DISABLED');
    INSERT INTO SERVICE_USAGE(BOOKING_ID,SERVICE_ID,QUANTITY,UNIT_PRICE_AT_USE,USAGE_DATE,USAGE_STATUS,RECORDED_BY)
    VALUES(p_booking,p_service,p_quantity,v_price,CASE WHEN p_status='USED' THEN CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP) ELSE CAST(v_booking.CHECK_IN_DATE AS TIMESTAMP) END,p_status,v_employee)
    RETURNING USAGE_ID INTO v_id;
    UPDATE BOOKINGS SET SERVICE_AMOUNT=SERVICE_AMOUNT+v_price*p_quantity,TOTAL_AMOUNT=TOTAL_AMOUNT+v_price*p_quantity WHERE BOOKING_ID=p_booking;
    AUDIT_EVENT(p_account,'ADD_SERVICE','SERVICE_USAGE',v_id); COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE; END;

  PROCEDURE RESOLVE_SERVICE(p_account NUMBER,p_usage NUMBER,p_status VARCHAR2) IS
    v_customer NUMBER; v_employee NUMBER; v_booking_id NUMBER; v_booking BOOKINGS%ROWTYPE; v_usage SERVICE_USAGE%ROWTYPE; v_day DATE:=HOTEL_DAY;
  BEGIN
    AUTHORIZE(p_account,'STAFF',v_customer,v_employee);
    SELECT BOOKING_ID INTO v_booking_id FROM SERVICE_USAGE WHERE USAGE_ID=p_usage;
    LOCK_BOOKING(v_booking_id,v_booking);
    SELECT * INTO v_usage FROM SERVICE_USAGE WHERE USAGE_ID=p_usage FOR UPDATE WAIT 5;
    REQUIRE_VALUE(v_booking.BOOKING_STATUS='CHECKED_IN' AND v_usage.USAGE_STATUS='PLANNED' AND p_status IN ('USED','CANCELLED'),-20003,'INVALID_STATE');
    UPDATE SERVICE_USAGE SET USAGE_STATUS=p_status,USAGE_DATE=CASE WHEN p_status='USED' THEN CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP) ELSE USAGE_DATE END,RECORDED_BY=v_employee WHERE USAGE_ID=p_usage;
    -- Prepaid planned package is non-refundable if unused during the stay.
    -- Cancellation here does not edit invoice totals or historical PAID amounts.
    AUDIT_EVENT(p_account,'RESOLVE_SERVICE','SERVICE_USAGE',p_usage,p_status); COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE; END;

  PROCEDURE REQUEST_CANCELLATION(p_account NUMBER,p_booking NUMBER,p_reason VARCHAR2) IS
    v_customer NUMBER; v_employee NUMBER; v_booking BOOKINGS%ROWTYPE; v_count NUMBER; v_id NUMBER;
  BEGIN
    AUTHORIZE(p_account,'OWN',v_customer,v_employee); LOCK_BOOKING(p_booking,v_booking); CHECK_OWNER(v_customer,v_employee,v_booking); CHECK_OPEN_BOOKING(v_booking);
    REQUIRE_VALUE(v_booking.BOOKING_STATUS IN ('PENDING_PAYMENT','CONFIRMED'),-20003,'INVALID_STATE');
    REQUIRE_VALUE(TRIM(p_reason) IS NOT NULL AND LENGTH(p_reason)<=500,-20018,'REASON_REQUIRED');
    SELECT COUNT(*) INTO v_count FROM CANCELLATION_REQUESTS WHERE BOOKING_ID=p_booking AND REQUEST_STATUS='PENDING';
    REQUIRE_VALUE(v_count=0,-20025,'CANCELLATION_ALREADY_REQUESTED');
    INSERT INTO CANCELLATION_REQUESTS(BOOKING_ID,REQUESTED_BY,REASON) VALUES(p_booking,p_account,p_reason) RETURNING REQUEST_ID INTO v_id;
    AUDIT_EVENT(p_account,'REQUEST_CANCELLATION','CANCELLATION_REQUESTS',v_id); COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE; END;

  PROCEDURE REVIEW_CANCELLATION(p_account NUMBER,p_request NUMBER,p_decision VARCHAR2,p_note VARCHAR2) IS
    v_customer NUMBER; v_employee NUMBER; v_booking_id NUMBER; v_booking BOOKINGS%ROWTYPE; v_request CANCELLATION_REQUESTS%ROWTYPE;
    v_refund NUMBER:=0; v_cancel NUMBER; v_check_in TIMESTAMP;
  BEGIN
    AUTHORIZE(p_account,'CANCEL',v_customer,v_employee);
    SELECT BOOKING_ID INTO v_booking_id FROM CANCELLATION_REQUESTS WHERE REQUEST_ID=p_request;
    LOCK_BOOKING(v_booking_id,v_booking);
    CHECK_OPEN_BOOKING(v_booking);
    SELECT * INTO v_request FROM CANCELLATION_REQUESTS WHERE REQUEST_ID=p_request FOR UPDATE WAIT 5;
    REQUIRE_VALUE(v_request.REQUEST_STATUS='PENDING' AND v_booking.BOOKING_STATUS IN ('PENDING_PAYMENT','CONFIRMED'),-20003,'INVALID_STATE');
    REQUIRE_VALUE(REVIEW_COUNT(v_booking_id)=0,-20026,'REVIEW_PAYMENT_FIRST');
    REQUIRE_VALUE(p_decision IN ('APPROVE','REJECT') AND TRIM(p_note) IS NOT NULL AND LENGTH(p_note)<=500,-20018,'REASON_REQUIRED');
    IF p_decision='APPROVE' THEN
      v_check_in:=CAST(v_booking.CHECK_IN_DATE+14/24 AS TIMESTAMP);
      IF v_request.CREATED_AT <= v_check_in-INTERVAL '2' DAY THEN v_refund:=PAID_AMOUNT(v_booking_id); END IF;
      INSERT INTO CANCELLATIONS(BOOKING_ID,CANCELLED_AT,CANCELLATION_REASON,REFUND_AMOUNT,APPROVED_BY)
      VALUES(v_booking_id,CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP),v_request.REASON,v_refund,v_employee) RETURNING CANCELLATION_ID INTO v_cancel;
      UPDATE BOOKINGS SET BOOKING_STATUS='CANCELLED' WHERE BOOKING_ID=v_booking_id;
      UPDATE SERVICE_USAGE SET USAGE_STATUS='CANCELLED' WHERE BOOKING_ID=v_booking_id AND USAGE_STATUS='PLANNED';
      IF v_refund>0 THEN INSERT INTO REFUNDS(CANCELLATION_ID,AMOUNT) VALUES(v_cancel,v_refund); END IF;
      -- Never change ROOMS to AVAILABLE on cancellation.
    END IF;
    UPDATE CANCELLATION_REQUESTS SET REQUEST_STATUS=CASE WHEN p_decision='APPROVE' THEN 'APPROVED' ELSE 'REJECTED' END,
      REVIEWED_BY=v_employee,REVIEWED_AT=CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP),REVIEW_NOTE=p_note WHERE REQUEST_ID=p_request;
    AUDIT_EVENT(p_account,'REVIEW_CANCELLATION','CANCELLATION_REQUESTS',p_request,p_decision); COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE; END;

  PROCEDURE COMPLETE_REFUND(p_account NUMBER,p_refund NUMBER,p_reference VARCHAR2) IS
    v_customer NUMBER; v_employee NUMBER; v_booking_id NUMBER; v_booking BOOKINGS%ROWTYPE; v_status VARCHAR2(20);
  BEGIN
    AUTHORIZE(p_account,'ADMIN',v_customer,v_employee);
    SELECT c.BOOKING_ID INTO v_booking_id FROM REFUNDS r JOIN CANCELLATIONS c ON c.CANCELLATION_ID=r.CANCELLATION_ID WHERE r.REFUND_ID=p_refund;
    LOCK_BOOKING(v_booking_id,v_booking);
    SELECT REFUND_STATUS INTO v_status FROM REFUNDS WHERE REFUND_ID=p_refund FOR UPDATE WAIT 5;
    REQUIRE_VALUE(v_status='PENDING' AND TRIM(p_reference) IS NOT NULL AND LENGTH(p_reference)<=100,-20027,'INVALID_REFUND');
    UPDATE REFUNDS SET REFUND_STATUS='REFUNDED',TRANSFER_REFERENCE=p_reference,COMPLETED_BY=v_employee,COMPLETED_AT=CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP) WHERE REFUND_ID=p_refund;
    AUDIT_EVENT(p_account,'COMPLETE_REFUND','REFUNDS',p_refund); COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE; END;

  PROCEDURE PREPARE_ROOM(p_account NUMBER,p_room NUMBER) IS
    v_customer NUMBER; v_employee NUMBER; v_count NUMBER; v_status VARCHAR2(20);
  BEGIN
    AUTHORIZE(p_account,'STAFF',v_customer,v_employee); LOCK_ROOM(p_room);
    SELECT ROOM_STATUS INTO v_status FROM ROOMS WHERE ROOM_ID=p_room;
    SELECT COUNT(*) INTO v_count FROM STAY_HISTORY h JOIN BOOKING_ROOMS br ON br.BOOKING_ID=h.BOOKING_ID WHERE br.ROOM_ID=p_room AND h.ACTUAL_CHECK_OUT IS NULL;
    REQUIRE_VALUE(v_status='CLEANING' AND v_count=0,-20022,'ROOM_NOT_READY');
    UPDATE ROOMS SET ROOM_STATUS='AVAILABLE',LAST_INSPECTION_DATE=TRUNC(CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS DATE)) WHERE ROOM_ID=p_room;
    AUDIT_EVENT(p_account,'PREPARE_ROOM','ROOMS',p_room); COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE; END;

  PROCEDURE EXPIRE_BOOKING(p_account NUMBER,p_booking NUMBER) IS
    v_customer NUMBER; v_employee NUMBER; v_booking BOOKINGS%ROWTYPE;
  BEGIN
    AUTHORIZE(p_account,'STAFF',v_customer,v_employee); LOCK_BOOKING(p_booking,v_booking);
    IF v_booking.BOOKING_STATUS='PENDING_PAYMENT' AND v_booking.EXPIRES_AT<=CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP) AND REVIEW_COUNT(p_booking)=0 THEN
      UPDATE BOOKINGS SET BOOKING_STATUS='EXPIRED' WHERE BOOKING_ID=p_booking;
      UPDATE SERVICE_USAGE SET USAGE_STATUS='CANCELLED' WHERE BOOKING_ID=p_booking AND USAGE_STATUS='PLANNED';
      UPDATE CANCELLATION_REQUESTS SET REQUEST_STATUS='REJECTED',REVIEWED_AT=CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP),REVIEWED_BY=v_employee,REVIEW_NOTE='Booking expired before review'
      WHERE BOOKING_ID=p_booking AND REQUEST_STATUS='PENDING';
      AUDIT_EVENT(p_account,'EXPIRE_BOOKING','BOOKINGS',p_booking);
    END IF;
    COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE; END;

  PROCEDURE SCHEDULE_MAINTENANCE(p_account NUMBER,p_room NUMBER,p_start DATE,p_end DATE,p_reason VARCHAR2) IS
    v_customer NUMBER; v_employee NUMBER; v_count NUMBER;
  BEGIN
    AUTHORIZE(p_account,'ADMIN',v_customer,v_employee); LOCK_ROOM(p_room);
    REQUIRE_VALUE(p_start=TRUNC(p_start) AND p_end=TRUNC(p_end) AND p_start>=HOTEL_DAY AND p_end>p_start AND TRIM(p_reason) IS NOT NULL AND LENGTH(p_reason)<=500,-20006,'INVALID_MAINTENANCE_DATES');
    REQUIRE_VALUE(ROOM_CONFLICTS(p_room,p_start,p_end)=0,-20009,'ROOM_ALLOCATED');
    SELECT COUNT(*) INTO v_count FROM ROOM_MAINTENANCE WHERE ROOM_ID=p_room AND START_DATE<p_end AND END_DATE>p_start;
    REQUIRE_VALUE(v_count=0,-20009,'MAINTENANCE_OVERLAP');
    INSERT INTO ROOM_MAINTENANCE(ROOM_ID,START_DATE,END_DATE,REASON,CREATED_BY) VALUES(p_room,p_start,p_end,p_reason,v_employee);
    AUDIT_EVENT(p_account,'SCHEDULE_MAINTENANCE','ROOMS',p_room); COMMIT;
  EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE; END;
