-- Ensure actual timestamps are recorded on every insert/update. No COMMIT in triggers.
DECLARE
  v_tables SYS.ODCIVARCHAR2LIST := SYS.ODCIVARCHAR2LIST('CUSTOMERS','EMPLOYEES','ROOM_TYPES','ROOMS','BOOKINGS','PROMOTIONS','SERVICES','SERVICE_USAGE','PAYMENTS','STAY_HISTORY','CANCELLATIONS','WEB_ACCOUNTS','CANCELLATION_REQUESTS','REFUNDS','ROOM_MAINTENANCE');
BEGIN
  FOR i IN 1 .. v_tables.COUNT LOOP
    EXECUTE IMMEDIATE 'CREATE OR REPLACE TRIGGER TS_' || v_tables(i) ||
      ' BEFORE INSERT OR UPDATE ON ' || v_tables(i) || ' FOR EACH ROW BEGIN ' ||
      ' IF INSERTING THEN :NEW.CREATED_AT := CAST(SYSTIMESTAMP AT TIME ZONE ''Asia/Bangkok'' AS TIMESTAMP); ELSE :NEW.CREATED_AT := :OLD.CREATED_AT; END IF; ' ||
      ' :NEW.UPDATED_AT := CAST(SYSTIMESTAMP AT TIME ZONE ''Asia/Bangkok'' AS TIMESTAMP); END;';
  END LOOP;
END;
/

-- ID generation is a proposed implementation; the diagram has NUMBER(10) PKs.
-- Separate insert triggers leave explicit sample IDs intact. Sequences are not transactional.
DECLARE
  v_tables SYS.ODCIVARCHAR2LIST := SYS.ODCIVARCHAR2LIST('CUSTOMERS','EMPLOYEES','ROOM_TYPES','ROOMS','PROMOTIONS','SERVICES','BOOKINGS','SERVICE_USAGE','PAYMENTS','STAY_HISTORY','CANCELLATIONS');
  v_keys SYS.ODCIVARCHAR2LIST := SYS.ODCIVARCHAR2LIST('CUSTOMER_ID','EMPLOYEE_ID','ROOM_TYPE_ID','ROOM_ID','PROMOTION_ID','SERVICE_ID','BOOKING_ID','USAGE_ID','PAYMENT_ID','STAY_ID','CANCELLATION_ID');
BEGIN
  FOR i IN 1..v_tables.COUNT LOOP
    EXECUTE IMMEDIATE 'CREATE SEQUENCE SQ_'||v_tables(i)||' START WITH 1000 MAXVALUE 9999999999 NOCYCLE';
    EXECUTE IMMEDIATE 'CREATE OR REPLACE TRIGGER ID_'||v_tables(i)||' BEFORE INSERT ON '||v_tables(i)||
      ' FOR EACH ROW BEGIN IF :NEW.'||v_keys(i)||' IS NULL THEN :NEW.'||v_keys(i)||' := SQ_'||v_tables(i)||'.NEXTVAL; END IF; END;';
  END LOOP;
END;
/
