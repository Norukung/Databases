CREATE TABLE CUSTOMERS (
  CUSTOMER_ID NUMBER(10) NOT NULL,
  FIRST_NAME VARCHAR2(100 CHAR) NOT NULL,
  LAST_NAME VARCHAR2(100 CHAR) NOT NULL,
  NATIONAL_ID VARCHAR2(13 CHAR),
  CREATED_AT TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP NOT NULL,
  DELETED_AT TIMESTAMP,
  CONSTRAINT PK_CUSTOMERS PRIMARY KEY (CUSTOMER_ID),
  CONSTRAINT UQ_CUSTOMERS_NATIONAL UNIQUE (NATIONAL_ID)
);

CREATE TABLE CUSTOMER_EMAILS (
  CUSTOMER_ID NUMBER(10) NOT NULL,
  EMAIL VARCHAR2(255 CHAR) NOT NULL,
  CONSTRAINT PK_CUSTOMER_EMAILS PRIMARY KEY (CUSTOMER_ID,EMAIL),
  CONSTRAINT FK_CE_CUSTOMERS FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(CUSTOMER_ID)
);

CREATE TABLE CUSTOMER_PHONES (
  CUSTOMER_ID NUMBER(10) NOT NULL,
  PHONE_NUMBER VARCHAR2(20 CHAR) NOT NULL,
  CONSTRAINT PK_CUSTOMER_PHONES PRIMARY KEY (CUSTOMER_ID,PHONE_NUMBER),
  CONSTRAINT FK_CP_CUSTOMERS FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(CUSTOMER_ID)
);

CREATE TABLE EMPLOYEES (
  EMPLOYEE_ID NUMBER(10) NOT NULL,
  FIRST_NAME VARCHAR2(100 CHAR) NOT NULL,
  LAST_NAME VARCHAR2(100 CHAR) NOT NULL,
  JOB_TITLE VARCHAR2(100 CHAR) NOT NULL,
  SYSTEM_ROLE VARCHAR2(10 CHAR) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP NOT NULL,
  DELETED_AT TIMESTAMP,
  CONSTRAINT PK_EMPLOYEES PRIMARY KEY (EMPLOYEE_ID)
);

CREATE TABLE EMPLOYEE_EMAILS (
  EMPLOYEE_ID NUMBER(10) NOT NULL,
  EMAIL VARCHAR2(255 CHAR) NOT NULL,
  CONSTRAINT PK_EMPLOYEE_EMAILS PRIMARY KEY (EMPLOYEE_ID,EMAIL),
  CONSTRAINT FK_EE_EMPLOYEES FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID)
);

CREATE TABLE EMPLOYEE_PHONES (
  EMPLOYEE_ID NUMBER(10) NOT NULL,
  PHONE_NUMBER VARCHAR2(20 CHAR) NOT NULL,
  CONSTRAINT PK_EMPLOYEE_PHONES PRIMARY KEY (EMPLOYEE_ID,PHONE_NUMBER),
  CONSTRAINT FK_EP_EMPLOYEES FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID)
