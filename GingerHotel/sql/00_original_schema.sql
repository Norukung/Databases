CREATE TABLE ROOM_TYPES (
  ROOM_TYPE_ID NUMBER(10) NOT NULL,
  TYPE_NAME VARCHAR2(100 CHAR) NOT NULL,
  DESCRIPTION VARCHAR2(500 CHAR),
  PRICE_PER_NIGHT NUMBER(12,2) NOT NULL,
  MAX_GUESTS NUMBER(3) NOT NULL,
  BED_COUNT NUMBER(3) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP NOT NULL,
  DELETED_AT TIMESTAMP,
  CONSTRAINT PK_ROOM_TYPES PRIMARY KEY (ROOM_TYPE_ID)
);

CREATE TABLE ROOMS (
  ROOM_ID NUMBER(10) NOT NULL,
  ROOM_TYPE_ID NUMBER(10) NOT NULL,
  ROOM_NUMBER VARCHAR2(20 CHAR) NOT NULL,
  FLOOR_NUMBER NUMBER(3) NOT NULL,
  ROOM_STATUS VARCHAR2(20 CHAR),
  LAST_INSPECTION_DATE DATE,
  CREATED_AT TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_ROOMS PRIMARY KEY (ROOM_ID),
  CONSTRAINT UQ_ROOMS_NUMBER UNIQUE (ROOM_NUMBER),
  CONSTRAINT FK_ROOMS_TYPE FOREIGN KEY (ROOM_TYPE_ID) REFERENCES ROOM_TYPES(ROOM_TYPE_ID)
);

CREATE TABLE PROMOTIONS (
  PROMOTION_ID NUMBER(10) NOT NULL,
  PROMOTION_NAME VARCHAR2(150 CHAR) NOT NULL,
  START_DATE DATE NOT NULL,
  END_DATE DATE NOT NULL,
  DISCOUNT_PERCENT NUMBER(5,2) NOT NULL,
  CONDITIONS VARCHAR2(1000 CHAR),
  CREATED_AT TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP NOT NULL,
  DELETED_AT TIMESTAMP,
  CONSTRAINT PK_PROMOTIONS PRIMARY KEY (PROMOTION_ID)
);

CREATE TABLE SERVICES (
  SERVICE_ID NUMBER(10) NOT NULL,
  SERVICE_NAME VARCHAR2(150 CHAR) NOT NULL,
  UNIT_PRICE NUMBER(12,2) NOT NULL,
  CATEGORY VARCHAR2(100 CHAR),
  SERVICE_STATUS VARCHAR2(20 CHAR) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP NOT NULL,
  DELETED_AT TIMESTAMP,
  CONSTRAINT PK_SERVICES PRIMARY KEY (SERVICE_ID)
);

CREATE TABLE BOOKINGS (
  BOOKING_ID NUMBER(10) NOT NULL,
  CUSTOMER_ID NUMBER(10) NOT NULL,
  EMPLOYEE_ID NUMBER(10),
  PROMOTION_ID NUMBER(10),
  GUEST_COUNT NUMBER(3) NOT NULL,
  BOOKING_STATUS VARCHAR2(20 CHAR) NOT NULL,
  CHECK_IN_DATE DATE NOT NULL,
  CHECK_OUT_DATE DATE NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_BOOKINGS PRIMARY KEY (BOOKING_ID),
  CONSTRAINT FK_BKG_CUSTOMERS FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(CUSTOMER_ID),
  CONSTRAINT FK_BKG_EMPLOYEES FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID),
  CONSTRAINT FK_BKG_PROMOTIONS FOREIGN KEY (PROMOTION_ID) REFERENCES PROMOTIONS(PROMOTION_ID)
);

CREATE TABLE BOOKING_ROOMS (
  BOOKING_ID NUMBER(10) NOT NULL,
  ROOM_ID NUMBER(10) NOT NULL,
  AGREED_PRICE_PER_NIGHT NUMBER(12,2) NOT NULL,
  CONSTRAINT PK_BOOKING_ROOMS PRIMARY KEY (BOOKING_ID,ROOM_ID),
  CONSTRAINT FK_BR_BOOKINGS FOREIGN KEY (BOOKING_ID) REFERENCES BOOKINGS(BOOKING_ID),
  CONSTRAINT FK_BR_ROOMS FOREIGN KEY (ROOM_ID) REFERENCES ROOMS(ROOM_ID)
);

CREATE TABLE SERVICE_USAGE (
  USAGE_ID NUMBER(10) NOT NULL,
  BOOKING_ID NUMBER(10) NOT NULL,
  SERVICE_ID NUMBER(10) NOT NULL,
  QUANTITY NUMBER(10) NOT NULL,
  USAGE_STATUS VARCHAR2(20 CHAR) NOT NULL,
  UNIT_PRICE_AT_USE NUMBER(12,2) NOT NULL,
  USAGE_DATE TIMESTAMP NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_SERVICE_USAGE PRIMARY KEY (USAGE_ID),
  CONSTRAINT FK_SU_BOOKINGS FOREIGN KEY (BOOKING_ID) REFERENCES BOOKINGS(BOOKING_ID),
  CONSTRAINT FK_SU_SERVICES FOREIGN KEY (SERVICE_ID) REFERENCES SERVICES(SERVICE_ID)
);

CREATE TABLE PAYMENTS (
  PAYMENT_ID NUMBER(10) NOT NULL,
  BOOKING_ID NUMBER(10) NOT NULL,
  PAYMENT_STATUS VARCHAR2(20 CHAR) NOT NULL,
  AMOUNT NUMBER(12,2) NOT NULL,
  PAYMENT_METHOD VARCHAR2(50 CHAR),
