  CONSTRAINT FK_PAY_BOOKINGS FOREIGN KEY (BOOKING_ID) REFERENCES BOOKINGS(BOOKING_ID)
);

CREATE TABLE STAY_HISTORY (
  STAY_ID NUMBER(10) NOT NULL,
  BOOKING_ID NUMBER(10) NOT NULL,
  EMPLOYEE_ID NUMBER(10) NOT NULL,
  ACTUAL_CHECK_IN TIMESTAMP NOT NULL,
  ACTUAL_CHECK_OUT TIMESTAMP,
  NOTES VARCHAR2(1000 CHAR),
  CREATED_AT TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_STAY_HISTORY PRIMARY KEY (STAY_ID),
  CONSTRAINT UQ_STAY_BOOKING UNIQUE (BOOKING_ID),
  CONSTRAINT FK_STAY_BOOKINGS FOREIGN KEY (BOOKING_ID) REFERENCES BOOKINGS(BOOKING_ID),
