-- Public procedures own the whole transaction. Helpers never COMMIT.
-- p_account comes only from authenticated backend session context.
SET DEFINE OFF;
CREATE OR REPLACE PACKAGE GINGER_MANAGEMENT AUTHID DEFINER AS
  PROCEDURE SAVE_MASTER(p_account NUMBER,p_entity VARCHAR2,p_id NUMBER,p_values CLOB,p_result_id OUT NUMBER);
  PROCEDURE UPDATE_PROFILE(p_account NUMBER,p_first VARCHAR2,p_last VARCHAR2,p_email VARCHAR2,p_phone VARCHAR2);
END GINGER_MANAGEMENT;
/
CREATE OR REPLACE PACKAGE BODY GINGER_MANAGEMENT AS
PROCEDURE SAVE_MASTER(p_account NUMBER,p_entity VARCHAR2,p_id NUMBER,p_values CLOB,p_result_id OUT NUMBER) IS
  v_account NUMBER:=p_account; v_entity VARCHAR2(30 CHAR):=p_entity;
  v_id NUMBER:=p_id; v_json CLOB:=p_values; v_employee NUMBER;
  v_role VARCHAR2(10 CHAR); v_active NUMBER; v_count NUMBER; v_lock NUMBER;
  v_old_room ROOMS%ROWTYPE;
  v_name VARCHAR2(200 CHAR); v_description VARCHAR2(1000 CHAR); v_first VARCHAR2(100 CHAR); v_last VARCHAR2(100 CHAR);
  v_email VARCHAR2(255 CHAR); v_phone VARCHAR2(20 CHAR); v_job VARCHAR2(100 CHAR); v_pay NUMBER; v_cancel NUMBER; v_deleted TIMESTAMP; v_price NUMBER; v_beds NUMBER; v_capacity NUMBER;
  v_size NUMBER; v_type NUMBER; v_floor NUMBER; v_number VARCHAR2(20 CHAR); v_status VARCHAR2(20 CHAR);
  v_new_role VARCHAR2(10 CHAR); v_percent NUMBER; v_code VARCHAR2(40 CHAR); v_nights NUMBER; v_min NUMBER; v_start DATE; v_end DATE;
  PROCEDURE REQUIRE_VALUE(p_ok BOOLEAN,p_message VARCHAR2) IS BEGIN
    IF p_ok IS NULL OR NOT p_ok THEN RAISE_APPLICATION_ERROR(-20030,p_message); END IF;
  END;
BEGIN
  SELECT e.EMPLOYEE_ID,e.SYSTEM_ROLE INTO v_employee,v_role FROM WEB_ACCOUNTS a JOIN EMPLOYEES e ON e.EMPLOYEE_ID=a.EMPLOYEE_ID
  WHERE a.ACCOUNT_ID=v_account AND a.IS_ACTIVE=1 AND e.DELETED_AT IS NULL;
  REQUIRE_VALUE(v_role='ADMIN' OR (v_role='STAFF' AND v_entity='customers' AND v_id IS NULL),'FORBIDDEN');
  REQUIRE_VALUE(v_entity IN ('customers','employees','rooms','roomTypes','services','promotions'),'UNKNOWN_ENTITY');
  v_active:=CASE JSON_VALUE(v_json,'$.active') WHEN 'true' THEN 1 WHEN 'false' THEN 0 ELSE NULL END;
  REQUIRE_VALUE(v_active IS NOT NULL,'ACTIVE_REQUIRED');
  v_deleted:=CASE WHEN v_active=1 THEN NULL ELSE CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP) END;
  v_job:=TRIM(JSON_VALUE(v_json,'$.jobTitle' RETURNING VARCHAR2(100 CHAR) ERROR ON ERROR));
  v_pay:=CASE JSON_VALUE(v_json,'$.canReviewPayments') WHEN 'true' THEN 1 ELSE 0 END;
  v_cancel:=CASE JSON_VALUE(v_json,'$.canReviewCancellations') WHEN 'true' THEN 1 ELSE 0 END;
  v_name:=TRIM(JSON_VALUE(v_json,'$.name')); v_description:=JSON_VALUE(v_json,'$.description' RETURNING VARCHAR2(1000 CHAR) ERROR ON ERROR);
  v_first:=TRIM(JSON_VALUE(v_json,'$.firstName')); v_last:=TRIM(JSON_VALUE(v_json,'$.lastName'));
  v_email:=LOWER(TRIM(JSON_VALUE(v_json,'$.email'))); v_phone:=TRIM(JSON_VALUE(v_json,'$.phone'));
  v_price:=JSON_VALUE(v_json,'$.price' RETURNING NUMBER ERROR ON ERROR);
  IF v_entity IN ('customers','employees') THEN
    REQUIRE_VALUE(v_first IS NOT NULL AND v_last IS NOT NULL AND REGEXP_LIKE(v_email,'^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$')
      AND REGEXP_LIKE(v_phone,'^[0-9+ -]{8,20}$'),'INVALID_CONTACT');
    IF v_entity='customers' THEN
      IF v_id IS NULL THEN INSERT INTO CUSTOMERS(FIRST_NAME,LAST_NAME,DELETED_AT) VALUES(v_first,v_last,v_deleted) RETURNING CUSTOMER_ID INTO v_id;
      ELSE UPDATE CUSTOMERS SET FIRST_NAME=v_first,LAST_NAME=v_last,DELETED_AT=v_deleted WHERE CUSTOMER_ID=v_id; REQUIRE_VALUE(SQL%ROWCOUNT=1,'NOT_FOUND'); END IF;
      UPDATE CUSTOMER_EMAILS SET IS_PRIMARY=0 WHERE CUSTOMER_ID=v_id AND IS_PRIMARY=1;
      MERGE INTO CUSTOMER_EMAILS t USING (SELECT v_id id,v_email email FROM DUAL) s ON (t.CUSTOMER_ID=s.id AND t.EMAIL=s.email)
      WHEN MATCHED THEN UPDATE SET t.IS_PRIMARY=1 WHEN NOT MATCHED THEN INSERT(CUSTOMER_ID,EMAIL,IS_PRIMARY) VALUES(s.id,s.email,1);
      UPDATE CUSTOMER_PHONES SET IS_PRIMARY=0 WHERE CUSTOMER_ID=v_id AND IS_PRIMARY=1;
      MERGE INTO CUSTOMER_PHONES t USING (SELECT v_id id,v_phone phone FROM DUAL) s ON (t.CUSTOMER_ID=s.id AND t.PHONE_NUMBER=s.phone)
      WHEN MATCHED THEN UPDATE SET t.IS_PRIMARY=1 WHEN NOT MATCHED THEN INSERT(CUSTOMER_ID,PHONE_NUMBER,IS_PRIMARY) VALUES(s.id,s.phone,1);
    ELSE
      -- Serialize role changes, then re-check the acting administrator's role.
      FOR e IN (SELECT EMPLOYEE_ID FROM EMPLOYEES WHERE SYSTEM_ROLE='ADMIN' AND DELETED_AT IS NULL ORDER BY EMPLOYEE_ID) LOOP
        SELECT EMPLOYEE_ID INTO v_lock FROM EMPLOYEES WHERE EMPLOYEE_ID=e.EMPLOYEE_ID FOR UPDATE WAIT 5;
      END LOOP;
      SELECT SYSTEM_ROLE INTO v_role FROM EMPLOYEES WHERE EMPLOYEE_ID=v_employee AND DELETED_AT IS NULL;
      REQUIRE_VALUE(v_role='ADMIN','FORBIDDEN');
      v_new_role:=JSON_VALUE(v_json,'$.role'); REQUIRE_VALUE(v_new_role IN ('STAFF','ADMIN'),'INVALID_ROLE');
      REQUIRE_VALUE(v_id IS NULL OR v_id<>v_employee OR (v_active=1 AND v_new_role='ADMIN'),'SELF_LOCKOUT');
      REQUIRE_VALUE(v_job IS NOT NULL,'JOB_TITLE_REQUIRED');
      IF v_id IS NULL THEN INSERT INTO EMPLOYEES(FIRST_NAME,LAST_NAME,JOB_TITLE,SYSTEM_ROLE,DELETED_AT) VALUES(v_first,v_last,v_job,v_new_role,v_deleted) RETURNING EMPLOYEE_ID INTO v_id;
      ELSE UPDATE EMPLOYEES SET FIRST_NAME=v_first,LAST_NAME=v_last,JOB_TITLE=v_job,SYSTEM_ROLE=v_new_role,DELETED_AT=v_deleted WHERE EMPLOYEE_ID=v_id; REQUIRE_VALUE(SQL%ROWCOUNT=1,'NOT_FOUND'); END IF;
      UPDATE EMPLOYEE_EMAILS SET IS_PRIMARY=0 WHERE EMPLOYEE_ID=v_id AND IS_PRIMARY=1;
      MERGE INTO EMPLOYEE_EMAILS t USING (SELECT v_id id,v_email email FROM DUAL) s ON (t.EMPLOYEE_ID=s.id AND t.EMAIL=s.email)
      WHEN MATCHED THEN UPDATE SET t.IS_PRIMARY=1 WHEN NOT MATCHED THEN INSERT(EMPLOYEE_ID,EMAIL,IS_PRIMARY) VALUES(s.id,s.email,1);
      UPDATE EMPLOYEE_PHONES SET IS_PRIMARY=0 WHERE EMPLOYEE_ID=v_id AND IS_PRIMARY=1;
      MERGE INTO EMPLOYEE_PHONES t USING (SELECT v_id id,v_phone phone FROM DUAL) s ON (t.EMPLOYEE_ID=s.id AND t.PHONE_NUMBER=s.phone)
      WHEN MATCHED THEN UPDATE SET t.IS_PRIMARY=1 WHEN NOT MATCHED THEN INSERT(EMPLOYEE_ID,PHONE_NUMBER,IS_PRIMARY) VALUES(s.id,s.phone,1);
      UPDATE WEB_ACCOUNTS SET CAN_REVIEW_PAYMENTS=v_pay,CAN_REVIEW_CANCELLATIONS=v_cancel WHERE EMPLOYEE_ID=v_id;
      -- Creating an employee does not automatically create login credentials or
      -- Oracle grants. Provision WEB_ACCOUNTS separately with a real hash.
    END IF;
  ELSIF v_entity='rooms' THEN
    v_type:=JSON_VALUE(v_json,'$.typeId' RETURNING NUMBER ERROR ON ERROR); v_floor:=JSON_VALUE(v_json,'$.floor' RETURNING NUMBER ERROR ON ERROR);
    v_number:=JSON_VALUE(v_json,'$.number'); v_status:=JSON_VALUE(v_json,'$.status');
    REQUIRE_VALUE(v_number IS NOT NULL AND v_floor=TRUNC(v_floor) AND v_floor>0,'INVALID_ROOM');
    IF v_id IS NOT NULL THEN
      SELECT * INTO v_old_room FROM ROOMS WHERE ROOM_ID=v_id FOR UPDATE WAIT 5;
      SELECT COUNT(*) INTO v_count FROM BOOKING_ROOMS br JOIN BOOKINGS b ON b.BOOKING_ID=br.BOOKING_ID
      WHERE br.ROOM_ID=v_id AND (b.BOOKING_STATUS IN ('CONFIRMED','CHECKED_IN') OR
        (b.BOOKING_STATUS='PENDING_PAYMENT' AND (b.EXPIRES_AT>CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP) OR EXISTS
          (SELECT 1 FROM PAYMENTS p WHERE p.BOOKING_ID=b.BOOKING_ID AND p.PAYMENT_STATUS='UNDER_REVIEW'))));
      REQUIRE_VALUE(v_count=0 OR (v_active=1 AND v_type=v_old_room.ROOM_TYPE_ID AND v_number=v_old_room.ROOM_NUMBER AND v_status=v_old_room.ROOM_STATUS),'ROOM_ALLOCATED');
      SELECT COUNT(*) INTO v_count FROM STAY_HISTORY h JOIN BOOKING_ROOMS br ON br.BOOKING_ID=h.BOOKING_ID WHERE br.ROOM_ID=v_id AND h.ACTUAL_CHECK_OUT IS NULL;
      REQUIRE_VALUE(v_count=0 OR (v_status='OCCUPIED' AND v_active=1),'ROOM_OCCUPIED');
      REQUIRE_VALUE(v_status IN ('AVAILABLE','CLEANING','MAINTENANCE') OR v_status=v_old_room.ROOM_STATUS,'INVALID_STATE');
      UPDATE ROOMS SET ROOM_TYPE_ID=v_type,ROOM_NUMBER=v_number,FLOOR_NUMBER=v_floor,ROOM_STATUS=v_status,IS_ACTIVE=v_active WHERE ROOM_ID=v_id;
    ELSE
      REQUIRE_VALUE(v_status IN ('AVAILABLE','CLEANING','MAINTENANCE'),'INVALID_STATE');
      INSERT INTO ROOMS(ROOM_TYPE_ID,ROOM_NUMBER,FLOOR_NUMBER,ROOM_STATUS,IS_ACTIVE) VALUES(v_type,v_number,v_floor,v_status,v_active) RETURNING ROOM_ID INTO v_id;
    END IF;
  ELSIF v_entity='roomTypes' THEN
    v_beds:=JSON_VALUE(v_json,'$.beds' RETURNING NUMBER ERROR ON ERROR); v_capacity:=JSON_VALUE(v_json,'$.capacity' RETURNING NUMBER ERROR ON ERROR);
    v_size:=JSON_VALUE(v_json,'$.size' RETURNING NUMBER ERROR ON ERROR);
    REQUIRE_VALUE(v_name IS NOT NULL AND LENGTH(v_name)<=100 AND (v_description IS NULL OR LENGTH(v_description)<=500),'INVALID_ROOM_TYPE_TEXT');
    REQUIRE_VALUE(v_beds=TRUNC(v_beds) AND v_capacity=TRUNC(v_capacity),'INTEGER_REQUIRED');
    IF v_id IS NULL THEN INSERT INTO ROOM_TYPES(TYPE_NAME,DESCRIPTION,PRICE_PER_NIGHT,BED_COUNT,MAX_GUESTS,AREA_SQM,DELETED_AT)
      VALUES(v_name,v_description,v_price,v_beds,v_capacity,v_size,v_deleted) RETURNING ROOM_TYPE_ID INTO v_id;
    ELSE UPDATE ROOM_TYPES SET TYPE_NAME=v_name,DESCRIPTION=v_description,PRICE_PER_NIGHT=v_price,BED_COUNT=v_beds,MAX_GUESTS=v_capacity,AREA_SQM=v_size,DELETED_AT=v_deleted WHERE ROOM_TYPE_ID=v_id; REQUIRE_VALUE(SQL%ROWCOUNT=1,'NOT_FOUND'); END IF;
  ELSIF v_entity='services' THEN
    REQUIRE_VALUE(v_name IS NOT NULL AND LENGTH(v_name)<=150,'INVALID_SERVICE_NAME');
    IF v_id IS NULL THEN INSERT INTO SERVICES(SERVICE_NAME,DESCRIPTION,UNIT_PRICE,SERVICE_STATUS,DELETED_AT) VALUES(v_name,v_description,v_price,CASE WHEN v_active=1 THEN 'ACTIVE' ELSE 'INACTIVE' END,v_deleted) RETURNING SERVICE_ID INTO v_id;
    ELSE UPDATE SERVICES SET SERVICE_NAME=v_name,DESCRIPTION=v_description,UNIT_PRICE=v_price,SERVICE_STATUS=CASE WHEN v_active=1 THEN 'ACTIVE' ELSE 'INACTIVE' END,DELETED_AT=v_deleted WHERE SERVICE_ID=v_id; REQUIRE_VALUE(SQL%ROWCOUNT=1,'NOT_FOUND'); END IF;
  ELSE
    REQUIRE_VALUE(v_name IS NOT NULL AND LENGTH(v_name)<=150,'INVALID_PROMOTION_NAME');
    v_code:=TRIM(JSON_VALUE(v_json,'$.code')); v_percent:=JSON_VALUE(v_json,'$.percent' RETURNING NUMBER ERROR ON ERROR);
    v_nights:=JSON_VALUE(v_json,'$.minNights' RETURNING NUMBER ERROR ON ERROR); v_min:=JSON_VALUE(v_json,'$.minAmount' RETURNING NUMBER ERROR ON ERROR);
    v_start:=TO_DATE(JSON_VALUE(v_json,'$.startDate'),'FXYYYY-MM-DD'); v_end:=TO_DATE(JSON_VALUE(v_json,'$.endDate'),'FXYYYY-MM-DD');
    REQUIRE_VALUE(v_nights=TRUNC(v_nights),'INTEGER_REQUIRED');
    IF v_id IS NULL THEN INSERT INTO PROMOTIONS(PROMOTION_NAME,PROMOTION_CODE,DISCOUNT_PERCENT,START_DATE,END_DATE,MIN_NIGHTS,MIN_ROOM_AMOUNT,DELETED_AT)
      VALUES(v_name,v_code,v_percent,v_start,v_end,v_nights,v_min,v_deleted) RETURNING PROMOTION_ID INTO v_id;
    ELSE UPDATE PROMOTIONS SET PROMOTION_NAME=v_name,PROMOTION_CODE=v_code,DISCOUNT_PERCENT=v_percent,START_DATE=v_start,END_DATE=v_end,MIN_NIGHTS=v_nights,MIN_ROOM_AMOUNT=v_min,DELETED_AT=v_deleted WHERE PROMOTION_ID=v_id; REQUIRE_VALUE(SQL%ROWCOUNT=1,'NOT_FOUND'); END IF;
  END IF;
  INSERT INTO AUDIT_LOG(ACCOUNT_ID,ACTION_NAME,ENTITY_NAME,ENTITY_ID) VALUES(v_account,'SAVE_MASTER',v_entity,v_id);
  p_result_id:=v_id; COMMIT;
EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
END SAVE_MASTER;

PROCEDURE UPDATE_PROFILE(p_account NUMBER,p_first VARCHAR2,p_last VARCHAR2,p_email VARCHAR2,p_phone VARCHAR2) IS
  v_customer NUMBER; v_email VARCHAR2(255 CHAR):=LOWER(TRIM(p_email)); v_phone VARCHAR2(20 CHAR):=TRIM(p_phone);
BEGIN
  SELECT a.CUSTOMER_ID INTO v_customer FROM WEB_ACCOUNTS a JOIN CUSTOMERS c ON c.CUSTOMER_ID=a.CUSTOMER_ID
  WHERE a.ACCOUNT_ID=p_account AND a.IS_ACTIVE=1 AND c.DELETED_AT IS NULL;
  IF TRIM(p_first) IS NULL OR TRIM(p_last) IS NULL OR LENGTH(p_first)>100 OR LENGTH(p_last)>100
    OR v_email IS NULL OR NOT REGEXP_LIKE(v_email,'^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$')
    OR v_phone IS NULL OR NOT REGEXP_LIKE(v_phone,'^[0-9+ -]{8,20}$') THEN
    RAISE_APPLICATION_ERROR(-20030,'INVALID_CONTACT');
  END IF;
  -- The parent update serializes simultaneous edits to the primary contacts.
  UPDATE CUSTOMERS SET FIRST_NAME=TRIM(p_first),LAST_NAME=TRIM(p_last) WHERE CUSTOMER_ID=v_customer;
  UPDATE CUSTOMER_EMAILS SET IS_PRIMARY=0 WHERE CUSTOMER_ID=v_customer AND IS_PRIMARY=1;
  MERGE INTO CUSTOMER_EMAILS t USING (SELECT v_customer id,v_email email FROM DUAL) s ON (t.CUSTOMER_ID=s.id AND t.EMAIL=s.email)
  WHEN MATCHED THEN UPDATE SET t.IS_PRIMARY=1 WHEN NOT MATCHED THEN INSERT(CUSTOMER_ID,EMAIL,IS_PRIMARY) VALUES(s.id,s.email,1);
  UPDATE CUSTOMER_PHONES SET IS_PRIMARY=0 WHERE CUSTOMER_ID=v_customer AND IS_PRIMARY=1;
  MERGE INTO CUSTOMER_PHONES t USING (SELECT v_customer id,v_phone phone FROM DUAL) s ON (t.CUSTOMER_ID=s.id AND t.PHONE_NUMBER=s.phone)
  WHEN MATCHED THEN UPDATE SET t.IS_PRIMARY=1 WHEN NOT MATCHED THEN INSERT(CUSTOMER_ID,PHONE_NUMBER,IS_PRIMARY) VALUES(s.id,s.phone,1);
  INSERT INTO AUDIT_LOG(ACCOUNT_ID,ACTION_NAME,ENTITY_NAME,ENTITY_ID) VALUES(p_account,'UPDATE_PROFILE','CUSTOMERS',v_customer);
  COMMIT;
EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
END UPDATE_PROFILE;
END GINGER_MANAGEMENT;
