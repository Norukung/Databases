SET DEFINE OFF;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

CREATE TABLE CUSTOMERS (
  CUSTOMER_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
  FIRST_NAME VARCHAR2(100 CHAR) NOT NULL, LAST_NAME VARCHAR2(100 CHAR) NOT NULL,
  NATIONAL_ID VARCHAR2(30 CHAR) UNIQUE,
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE CUSTOMER_EMAILS (
  CUSTOMER_ID NUMBER REFERENCES CUSTOMERS(CUSTOMER_ID), EMAIL VARCHAR2(254 CHAR),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_CUSTOMER_EMAILS PRIMARY KEY (CUSTOMER_ID, EMAIL)
);
CREATE TABLE CUSTOMER_PHONES (
  CUSTOMER_ID NUMBER REFERENCES CUSTOMERS(CUSTOMER_ID), PHONE VARCHAR2(30 CHAR),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_CUSTOMER_PHONES PRIMARY KEY (CUSTOMER_ID, PHONE)
);
CREATE TABLE EMPLOYEES (
  EMPLOYEE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
  FIRST_NAME VARCHAR2(100 CHAR) NOT NULL, LAST_NAME VARCHAR2(100 CHAR) NOT NULL,
  POSITION_NAME VARCHAR2(100 CHAR),
  SYSTEM_ROLE VARCHAR2(10 CHAR) NOT NULL CHECK (SYSTEM_ROLE IN ('STAFF','ADMIN')),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE EMPLOYEE_EMAILS (
  EMPLOYEE_ID NUMBER REFERENCES EMPLOYEES(EMPLOYEE_ID), EMAIL VARCHAR2(254 CHAR),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_EMPLOYEE_EMAILS PRIMARY KEY (EMPLOYEE_ID, EMAIL)
);
CREATE TABLE EMPLOYEE_PHONES (
  EMPLOYEE_ID NUMBER REFERENCES EMPLOYEES(EMPLOYEE_ID), PHONE VARCHAR2(30 CHAR),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_EMPLOYEE_PHONES PRIMARY KEY (EMPLOYEE_ID, PHONE)
);
CREATE TABLE ROOM_TYPES (
  ROOM_TYPE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
  TYPE_NAME VARCHAR2(100 CHAR) NOT NULL, DESCRIPTION VARCHAR2(1000 CHAR),
  PRICE_PER_NIGHT NUMBER(12,2) NOT NULL CHECK (PRICE_PER_NIGHT > 0),
  BED_COUNT NUMBER(3) NOT NULL CHECK (BED_COUNT > 0),
  MAX_GUESTS NUMBER(3) NOT NULL CHECK (MAX_GUESTS >= BED_COUNT),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE ROOMS (
  ROOM_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
  ROOM_TYPE_ID NUMBER NOT NULL REFERENCES ROOM_TYPES(ROOM_TYPE_ID),
  ROOM_NUMBER VARCHAR2(20 CHAR) NOT NULL UNIQUE, FLOOR_NUMBER NUMBER(3) NOT NULL,
  ROOM_STATUS VARCHAR2(20 CHAR) DEFAULT 'AVAILABLE' NOT NULL
    CHECK (ROOM_STATUS IN ('AVAILABLE','OCCUPIED','CLEANING','MAINTENANCE')),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE PROMOTIONS (
  PROMOTION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
  PROMOTION_NAME VARCHAR2(150 CHAR) NOT NULL, PROMOTION_CODE VARCHAR2(40 CHAR) NOT NULL UNIQUE,
  DISCOUNT_PERCENT NUMBER(5,2) NOT NULL CHECK (DISCOUNT_PERCENT > 0 AND DISCOUNT_PERCENT < 100),
  START_DATE DATE NOT NULL, END_DATE DATE NOT NULL, TERMS VARCHAR2(1000 CHAR),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CHECK (END_DATE >= START_DATE)
);
CREATE TABLE SERVICES (
  SERVICE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
  SERVICE_NAME VARCHAR2(150 CHAR) NOT NULL, CATEGORY VARCHAR2(100 CHAR), DESCRIPTION VARCHAR2(1000 CHAR),
  UNIT_PRICE NUMBER(12,2) NOT NULL CHECK (UNIT_PRICE > 0),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE BOOKINGS (
  BOOKING_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
  CUSTOMER_ID NUMBER NOT NULL REFERENCES CUSTOMERS(CUSTOMER_ID),
  EMPLOYEE_ID NUMBER REFERENCES EMPLOYEES(EMPLOYEE_ID),
  PROMOTION_ID NUMBER REFERENCES PROMOTIONS(PROMOTION_ID),
  BOOKING_DATE TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CHECK_IN_DATE DATE NOT NULL, CHECK_OUT_DATE DATE NOT NULL,
  GUEST_COUNT NUMBER(3) NOT NULL CHECK (GUEST_COUNT > 0),
  BOOKING_STATUS VARCHAR2(20 CHAR) DEFAULT 'PENDING_PAYMENT' NOT NULL
    CHECK (BOOKING_STATUS IN ('PENDING_PAYMENT','CONFIRMED','CHECKED_IN','CHECKED_OUT','CANCELLED','EXPIRED')),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CHECK (CHECK_OUT_DATE > CHECK_IN_DATE),
  CHECK (CHECK_IN_DATE = TRUNC(CHECK_IN_DATE) AND CHECK_OUT_DATE = TRUNC(CHECK_OUT_DATE))
);
CREATE TABLE BOOKING_ROOMS (
  BOOKING_ID NUMBER REFERENCES BOOKINGS(BOOKING_ID), ROOM_ID NUMBER REFERENCES ROOMS(ROOM_ID),
  AGREED_PRICE_PER_NIGHT NUMBER(12,2) NOT NULL CHECK (AGREED_PRICE_PER_NIGHT > 0),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_BOOKING_ROOMS PRIMARY KEY (BOOKING_ID, ROOM_ID)
);
CREATE TABLE SERVICE_USAGE (
  SERVICE_USAGE_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
  BOOKING_ID NUMBER NOT NULL REFERENCES BOOKINGS(BOOKING_ID), SERVICE_ID NUMBER NOT NULL REFERENCES SERVICES(SERVICE_ID),
  QUANTITY NUMBER(3) NOT NULL CHECK (QUANTITY > 0),
  UNIT_PRICE_AT_USE NUMBER(12,2) NOT NULL CHECK (UNIT_PRICE_AT_USE > 0),
  USAGE_DATE DATE NOT NULL,
  USAGE_STATUS VARCHAR2(20 CHAR) DEFAULT 'PLANNED' NOT NULL CHECK (USAGE_STATUS IN ('PLANNED','USED','CANCELLED')),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE PAYMENTS (
  PAYMENT_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
  BOOKING_ID NUMBER NOT NULL REFERENCES BOOKINGS(BOOKING_ID),
  AMOUNT NUMBER(12,2) NOT NULL CHECK (AMOUNT > 0),
  PAYMENT_DATE TIMESTAMP WITH TIME ZONE,
  PAYMENT_METHOD VARCHAR2(20 CHAR) CHECK (PAYMENT_METHOD IN ('BANK_TRANSFER','PROMPTPAY')),
  PROOF_PATH VARCHAR2(500 CHAR),
  PAYMENT_STATUS VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL CHECK (PAYMENT_STATUS IN ('PENDING','UNDER_REVIEW','PAID','REJECTED')),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE STAY_HISTORY (
  STAY_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
  BOOKING_ID NUMBER NOT NULL UNIQUE REFERENCES BOOKINGS(BOOKING_ID),
  EMPLOYEE_ID NUMBER NOT NULL REFERENCES EMPLOYEES(EMPLOYEE_ID),
  ACTUAL_CHECK_IN TIMESTAMP WITH TIME ZONE NOT NULL, ACTUAL_CHECK_OUT TIMESTAMP WITH TIME ZONE,
  NOTES VARCHAR2(1000 CHAR),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CHECK (ACTUAL_CHECK_OUT IS NULL OR ACTUAL_CHECK_OUT >= ACTUAL_CHECK_IN)
);
CREATE TABLE CANCELLATIONS (
  CANCELLATION_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1000) PRIMARY KEY,
  BOOKING_ID NUMBER NOT NULL UNIQUE REFERENCES BOOKINGS(BOOKING_ID),
  CANCELLATION_DATE TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  REASON VARCHAR2(500 CHAR) NOT NULL, REFUND_AMOUNT NUMBER(12,2) DEFAULT 0 NOT NULL CHECK (REFUND_AMOUNT >= 0),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IX_ROOMS_TYPE ON ROOMS(ROOM_TYPE_ID);
CREATE INDEX IX_BR_ROOM ON BOOKING_ROOMS(ROOM_ID, BOOKING_ID);
CREATE INDEX IX_BOOKING_CUSTOMER ON BOOKINGS(CUSTOMER_ID);
CREATE INDEX IX_BOOKING_DATES ON BOOKINGS(BOOKING_STATUS, CHECK_IN_DATE, CHECK_OUT_DATE);
CREATE INDEX IX_BOOKING_EMPLOYEE ON BOOKINGS(EMPLOYEE_ID);
CREATE INDEX IX_BOOKING_PROMO ON BOOKINGS(PROMOTION_ID);
CREATE INDEX IX_USAGE_BOOKING ON SERVICE_USAGE(BOOKING_ID);
CREATE INDEX IX_USAGE_SERVICE ON SERVICE_USAGE(SERVICE_ID);
CREATE INDEX IX_PAYMENT_BOOKING ON PAYMENTS(BOOKING_ID, PAYMENT_STATUS);
CREATE INDEX IX_STAY_EMPLOYEE ON STAY_HISTORY(EMPLOYEE_ID);
