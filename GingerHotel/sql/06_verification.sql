SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS WHERE STATUS <> 'VALID';
SELECT NAME, TYPE, LINE, POSITION, TEXT FROM USER_ERRORS ORDER BY NAME, SEQUENCE;
SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE, STATUS FROM USER_CONSTRAINTS
WHERE STATUS <> 'ENABLED';

-- All following integrity checks should return zero rows.
SELECT b.BOOKING_ID FROM BOOKINGS b WHERE b.ROOM_AMOUNT <> (
  SELECT NVL(SUM(br.AGREED_PRICE_PER_NIGHT*(b.CHECK_OUT_DATE-b.CHECK_IN_DATE)),-1)
  FROM BOOKING_ROOMS br WHERE br.BOOKING_ID=b.BOOKING_ID);
SELECT b.BOOKING_ID FROM BOOKINGS b WHERE b.SERVICE_AMOUNT <>
  NVL((SELECT SUM(u.QUANTITY*u.UNIT_PRICE_AT_USE) FROM SERVICE_USAGE u WHERE u.BOOKING_ID=b.BOOKING_ID),0);
SELECT BOOKING_ID FROM BOOKINGS WHERE TOTAL_AMOUNT<>ROOM_AMOUNT+SERVICE_AMOUNT-DISCOUNT_AMOUNT;
SELECT BOOKING_ID FROM PAYMENTS WHERE PAYMENT_STATUS='PAID' GROUP BY BOOKING_ID
HAVING SUM(AMOUNT) > (SELECT TOTAL_AMOUNT FROM BOOKINGS b WHERE b.BOOKING_ID=PAYMENTS.BOOKING_ID);
SELECT br1.ROOM_ID,b1.BOOKING_ID,b2.BOOKING_ID AS CONFLICT_BOOKING
FROM BOOKING_ROOMS br1 JOIN BOOKINGS b1 ON b1.BOOKING_ID=br1.BOOKING_ID
JOIN BOOKING_ROOMS br2 ON br1.ROOM_ID=br2.ROOM_ID AND br1.BOOKING_ID<br2.BOOKING_ID
JOIN BOOKINGS b2 ON b2.BOOKING_ID=br2.BOOKING_ID
WHERE (b1.BOOKING_STATUS IN ('CONFIRMED','CHECKED_IN') OR (b1.BOOKING_STATUS='PENDING_PAYMENT' AND
  (b1.EXPIRES_AT>CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP) OR EXISTS
    (SELECT 1 FROM PAYMENTS p WHERE p.BOOKING_ID=b1.BOOKING_ID AND p.PAYMENT_STATUS='UNDER_REVIEW'))))
AND (b2.BOOKING_STATUS IN ('CONFIRMED','CHECKED_IN') OR (b2.BOOKING_STATUS='PENDING_PAYMENT' AND
  (b2.EXPIRES_AT>CAST(SYSTIMESTAMP AT TIME ZONE 'Asia/Bangkok' AS TIMESTAMP) OR EXISTS
    (SELECT 1 FROM PAYMENTS p WHERE p.BOOKING_ID=b2.BOOKING_ID AND p.PAYMENT_STATUS='UNDER_REVIEW'))))
AND b1.CHECK_IN_DATE<b2.CHECK_OUT_DATE AND b1.CHECK_OUT_DATE>b2.CHECK_IN_DATE;

SELECT m1.MAINTENANCE_ID,m2.MAINTENANCE_ID AS CONFLICT_MAINTENANCE
FROM ROOM_MAINTENANCE m1 JOIN ROOM_MAINTENANCE m2 ON m1.ROOM_ID=m2.ROOM_ID AND m1.MAINTENANCE_ID<m2.MAINTENANCE_ID
WHERE m1.START_DATE<m2.END_DATE AND m1.END_DATE>m2.START_DATE;
SELECT h.STAY_ID,r.ROOM_ID FROM STAY_HISTORY h
JOIN BOOKING_ROOMS br ON br.BOOKING_ID=h.BOOKING_ID JOIN ROOMS r ON r.ROOM_ID=br.ROOM_ID
WHERE h.ACTUAL_CHECK_OUT IS NULL AND r.ROOM_STATUS<>'OCCUPIED';

